"""Generate tests/reference_data.rs from independent Python implementations.

    pip install -r tools/requirements.txt
    python tools/gen_reference.py > tests/reference_data.rs && cargo fmt

The signals are rebuilt bit for bit in tests/reference.rs from the same
64-bit LCG, so only the expected outputs are stored.
"""
from importlib.metadata import version

import numpy as np
import MFDFA as mfdfa_pkg
import antropy
import antropy.utils
import pywt

MASK = (1 << 64) - 1


def lcg_uniform(n, seed):
    s, out = seed, []
    for _ in range(n):
        s = (s * 6364136223846793005 + 1442695040888963407) & MASK
        out.append((s >> 11) / float(1 << 53))
    return np.array(out)


def cascade(levels, p, seed):
    """Binomial p-model cascade with LCG-chosen left/right weights."""
    s, v = seed, [1.0]
    for _ in range(levels):
        nxt = []
        for x in v:
            s = (s * 6364136223846793005 + 1442695040888963407) & MASK
            if (s >> 63) & 1:
                nxt += [x * p, x * (1.0 - p)]
            else:
                nxt += [x * (1.0 - p), x * p]
        v = nxt
    return np.array(v)


def signal_a():
    # Uniform noise modulated by a multiplicative cascade: multifractal.
    n = 4096
    return (lcg_uniform(n, 12345) - 0.5) * cascade(12, 0.35, 777) * n


def signal_b():
    # Plain uniform noise, 3000 points (not a power of two).
    return lcg_uniform(3000, 2024) - 0.5


def q_avg_log(F2):
    return np.exp(0.5 * np.mean(np.log(F2)))


def mfdfa_ref(x, q, scales, order):
    q = np.asarray(q, dtype=float)
    nz = q[q != 0.0]
    lag, F = mfdfa_pkg.MFDFA(x, lag=np.array(scales), q=nz, order=order)
    assert list(lag) == list(scales)
    Fq = np.empty((len(q), len(scales)))
    Fq[q != 0.0, :] = F.T
    if (q == 0.0).any():
        # The MFDFA package skips q = 0; use the logarithmic average.
        Y = np.cumsum(x - x.mean())
        N = len(Y)
        X = np.arange(1, max(scales) + 1, dtype=float)
        row = []
        for s in scales:
            Yf = Y[: N - N % s].reshape(-1, s)
            Yr = Y[N % s:].reshape(-1, s)
            F2 = []
            for seg in np.vstack([Yf, Yr]):
                c = np.polynomial.polynomial.polyfit(X[:s], seg, order)
                F2.append(np.var(seg - np.polynomial.polynomial.polyval(X[:s], c)))
            row.append(q_avg_log(np.array(F2)))
        Fq[q == 0.0, :] = row
    ls = np.log(np.array(scales, dtype=float))
    h = np.array([np.polyfit(ls, np.log(r), 1)[0] for r in Fq])
    tau = q * h - 1.0
    alpha = np.gradient(tau, q)
    f = q * alpha - tau
    return Fq, h, tau, alpha, f


def wavelet_ref(x):
    cur = np.asarray(x, dtype=float)
    js, ys, ns = [], [], []
    j = 0
    while True:
        if len(cur) % 2 == 1:
            cur = cur[:-1]
        if len(cur) < 16:
            break
        j += 1
        a, d = pywt.dwt(cur, "db4", mode="periodization")
        js.append(j)
        ys.append(np.log2(np.mean(d * d)))
        ns.append(len(d))
        cur = a
    slope = np.polyfit(js, ys, 1, w=np.sqrt(ns))[0]
    return (slope + 1.0) / 2.0, ys


def antropy_higuchi(x, k_max):
    """antropy.higuchi_fd with its regression epsilon removed.

    antropy computes slope = num / (den + 1e-9); undo that offset so the
    reference is the plain least-squares slope over ln(1/k).
    """
    d = antropy.higuchi_fd(x, kmax=k_max)
    lx = np.log(1.0 / np.arange(1, k_max + 1))
    n = len(lx)
    den = n * np.sum(lx ** 2) - np.sum(lx) ** 2
    return d * (den + antropy.utils.epsilon) / den


def arr(name, v):
    body = ", ".join(repr(float(t)) for t in np.ravel(v))
    return f"pub const {name}: [f64; {np.size(v)}] = [{body}];\n"


def main():
    out = ["// @generated by tools/gen_reference.py. Do not edit by hand.\n",
           "// " + ", ".join(f"{p} {version(p)}" for p in ("numpy", "MFDFA", "antropy", "PyWavelets")) + "\n",
           "#![allow(dead_code, clippy::approx_constant, clippy::excessive_precision)]\n\n"]
    a, b = signal_a(), signal_b()
    out.append(arr("SIGNAL_A_HEAD", a[:8]))
    out.append(arr("SIGNAL_B_HEAD", b[:8]))

    q = [-4.0, -3.0, -2.0, -1.0, 0.0, 1.0, 2.0, 3.0, 4.0]
    scales = [16, 24, 32, 48, 64, 96, 128, 192, 256]
    out.append(arr("Q", q))
    out.append(f"pub const SCALES: [usize; {len(scales)}] = {scales};\n")
    for tag, x in (("A", a), ("B", b)):
        for order in (1, 2, 3):
            Fq, h, tau, alpha, f = mfdfa_ref(x, q, scales, order)
            k = f"{tag}_O{order}"
            out.append(arr(f"FQ_{k}", Fq))
            out.append(arr(f"HQ_{k}", h))
            out.append(arr(f"TAU_{k}", tau))
            out.append(arr(f"ALPHA_{k}", alpha))
            out.append(arr(f"FALPHA_{k}", f))

    path_a, path_b = np.cumsum(a), np.cumsum(b)
    kmax = [2, 5, 10, 16, 32]
    out.append(f"pub const KMAX: [usize; {len(kmax)}] = {kmax};\n")
    out.append(arr("HIGUCHI_PATH_A", [antropy_higuchi(path_a, k) for k in kmax]))
    out.append(arr("HIGUCHI_PATH_B", [antropy_higuchi(path_b, k) for k in kmax]))
    out.append(arr("HIGUCHI_NOISE_B", [antropy_higuchi(b, k) for k in kmax]))

    ca, cd = pywt.dwt(a[:256], "db4", mode="periodization")
    out.append(arr("DWT_A256_APPROX", ca))
    out.append(arr("DWT_A256_DETAIL", cd))
    for tag, x in (("A", a), ("B", b)):
        h, ys = wavelet_ref(x)
        out.append(arr(f"WAVELET_H_{tag}", [h]))
        out.append(arr(f"WAVELET_LOG2E_{tag}", ys))
    print("".join(out), end="")


if __name__ == "__main__":
    main()
